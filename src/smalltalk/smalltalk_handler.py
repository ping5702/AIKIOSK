from typing import Optional

# 장소 검색(RAG)과 분리된 인사/잡담 규칙. 키워드가 매칭되면 고정 응답을 반환한다.
# 장소명과 겹칠 만한 모호한 키워드(예: "몇 시", "날짜")는 운영시간 등 실제 RAG 질문을
# 가로챌 위험이 있어 의도적으로 넣지 않았다.
_SMALLTALK_RULES = [
    (("안녕", "hi", "hello", "반가워"), "안녕하세요! 궁금하신 시설이나 장소를 말씀해 주세요."),
    (("고마워", "고맙", "감사"), "천만에요! 더 필요한 안내가 있으신가요?"),
    (("잘가", "안녕히", "bye", "수고하"), "안녕히 가세요! 좋은 하루 되세요."),
    (("누구야", "누구세요", "너 뭐야", "너의 정체", "정체가 뭐"), "저는 이 건물 안내를 도와드리는 AI 키오스크예요. 부서나 회의실 위치를 편하게 물어보세요."),
    (("뭘 할 수 있", "뭐 물어보면", "사용법", "어떻게 써", "무슨 질문"), "부서 위치, 회의실, 연락처 같은 걸 물어보시면 제가 찾아서 안내해 드려요."),
    (("잘한다", "똑똑하", "대단해", "멋지다", "신기하다"), "감사합니다! 더 궁금하신 게 있으면 말씀해 주세요."),
    (("심심해", "재미없어", "지루해"), "심심하시군요! 그래도 궁금한 장소가 있으면 언제든 물어봐 주세요."),
]


def match_smalltalk(query: str) -> Optional[str]:
    """질문이 인사/잡담이면 고정 응답을, 아니면 None을 반환한다."""
    normalized = query.strip()
    for keywords, response in _SMALLTALK_RULES:
        if any(keyword in normalized for keyword in keywords):
            return response
    return None
